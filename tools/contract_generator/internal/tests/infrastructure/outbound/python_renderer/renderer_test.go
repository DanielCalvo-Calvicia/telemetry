func check_style(test *testing.T, name string, content string) {
	test.Helper()
	if strings.Contains(content, "\r") || strings.Contains(content, "\t") || !strings.HasSuffix(content, "\n") || strings.HasSuffix(content, "\n\n") {
		test.Errorf("%s: line ends, tabs or the final newline are wrong", name)
	}
	for _, line := range strings.Split(content, "\n") {
		if len(line) > 120 {
			test.Errorf("%s: a line is longer than 120 characters: %s", name, line)
		}
	}
	if !strings.HasPrefix(content, "# Code generated by contract_generator; DO NOT EDIT.\n") {
		test.Errorf("%s does not start with the generated header and its source", name)
	}
}

func TestTheFixtureContractRendersTheExpectedPythonFiles(test *testing.T) {
	contract, read_error := contract_folder.NewReader(external.NewFolder(fixtures.ContractDir())).Read()
	if read_error != nil {
		test.Fatal(read_error)
	}
	files, render_error := python_renderer.NewRenderer().Render(contract.Sorted())
	if render_error != nil {
		test.Fatal(render_error)
	}
	if len(files) != 4 {
		test.Fatalf("got %d files, want 4", len(files))
	}
	for _, generated := range files {
		if expected := fixtures.Expected(test, "python/"+generated.Name+".golden"); string(generated.Content) != expected {
			test.Errorf("%s differs from its expected file:\n%s", generated.Name, generated.Content)
		}
		check_style(test, generated.Name, string(generated.Content))
	}
}

func TestAnEmptyContractRendersValidPython(test *testing.T) {
	files, render_error := python_renderer.NewRenderer().Render(domain.Contract{})
	if render_error != nil {
		test.Fatal(render_error)
	}
	for _, generated := range files {
		check_style(test, generated.Name, string(generated.Content))
	}
	if !strings.Contains(string(files[1].Content), "EVENT_TYPES: tuple[str, ...] = ()") ||
		!strings.Contains(string(files[2].Content), "ERROR_CODES: dict[str, ErrorCodeInfo] = {}") {
		test.Error("an empty registry and an empty catalog render as an empty tuple and an empty dict")
	}
}

func TestALongMessageIsWrappedAndAWordLongerThanALineIsKept(test *testing.T) {
	long_word := strings.Repeat("x", 130)
	contract := domain.Contract{ErrorCodes: []domain.ErrorCode{
		{Code: "long_words", Category: "validation", DefaultMessage: "start " + long_word + " middle " + long_word + " end", Source: "contracts/errors/catalog.yaml"},
	}}
	files, render_error := python_renderer.NewRenderer().Render(contract)
	if render_error != nil {
		test.Fatal(render_error)
	}
	text := string(files[2].Content)
	for _, expected := range []string{"default_message=(\n", "\"start \"\n", "\"middle \"\n", "\"end\"\n"} {
		if !strings.Contains(text, expected) {
			test.Errorf("missing %q in\n%s", expected, text)
		}
	}
}

func TestEveryKindOfFieldHasItsAnnotation(test *testing.T) {
	contract := domain.Contract{Structs: []domain.Struct{{Name: "thing", Source: "contracts/schemas/thing.schema.json", Fields: []domain.Field{
		{JSONName: "ratio", Kind: domain.KindNumber, Required: true},
		{JSONName: "count", Kind: domain.KindInteger},
		{JSONName: "flag", Kind: domain.KindBoolean},
		{JSONName: "kind", Kind: domain.KindEnum, Ref: "severity"},
		{JSONName: "level", Kind: domain.KindEnum, Ref: "actor_kind"},
		{JSONName: "inner", Kind: domain.KindStruct, Ref: "thing"},
		{JSONName: "extra", Kind: domain.KindMap},
	}}}}
	files, _ := python_renderer.NewRenderer().Render(contract)
	text := string(files[3].Content)
	for _, expected := range []string{"ratio: float\n", "count: int | None = None", "flag: bool | None = None", "kind: Severity | None = None",
		"inner: Thing | None = None", "extra: dict[str, Any] | None = None", "import ActorKind, Severity\n"} {
		if !strings.Contains(text, expected) {
			test.Errorf("missing %q in\n%s", expected, text)
		}
	}
}
