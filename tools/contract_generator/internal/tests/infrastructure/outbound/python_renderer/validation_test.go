// check_validation_style fails the test if the Python has a line over 120 characters, a tab, a carriage return or trailing spaces.
func check_validation_style(test *testing.T, content string) {
	test.Helper()
	if strings.Contains(content, "\r") || strings.Contains(content, "\t") || !strings.HasSuffix(content, "\n") || strings.HasSuffix(content, "\n\n") {
		test.Error("the file must use LF, no tabs and end with exactly one line end")
	}
	for number, line := range strings.Split(content, "\n") {
		if len(line) > 120 || strings.HasSuffix(line, " ") {
			test.Errorf("line %d is too long or ends with a space: %q", number+1, line)
		}
	}
}

func TestTheFixtureContractRendersTheExpectedPythonValidators(test *testing.T) {
	contract, read_error := contract_folder.NewReader(external.NewFolder(fixtures.ContractDir())).Read()
	if read_error != nil {
		test.Fatal(read_error)
	}
	files, render_error := python_renderer.NewValidationRenderer().Render(contract.Sorted())
	if render_error != nil {
		test.Fatal(render_error)
	}
	if len(files) != 1 || files[0].Name != "event_validators_generated.py" {
		test.Fatalf("files: %+v", files)
	}
	if expected := fixtures.Expected(test, "python/event_validators_generated.py.golden"); string(files[0].Content) != expected {
		test.Errorf("the validators differ from their expected file:\n%s", files[0].Content)
	}
	check_validation_style(test, string(files[0].Content))
	if !strings.HasPrefix(string(files[0].Content), "# Code generated by contract_generator; DO NOT EDIT.\n# Source: contracts/enums/severity.json\n") {
		test.Error("the file must start with the generated marker and its sources")
	}
}

func TestAContractWithNoEventTypeRendersAnEmptyTableAndImportsOnlyWhatItUses(test *testing.T) {
	files, render_error := python_renderer.NewValidationRenderer().Render(domain.Contract{})
	if render_error != nil {
		test.Fatal(render_error)
	}
	content := string(files[0].Content)
	if !strings.Contains(content, "EVENT_VALIDATORS: dict[str, Validator] = {}\n") ||
		!strings.Contains(content, "import Validator\n") || strings.Contains(content, "typing") || strings.Contains(content, "def ") {
		test.Errorf("content:\n%s", content)
	}
	check_validation_style(test, content)
}

func TestEveryKindOfFieldHasItsCheckAndLongLinesAreWrapped(test *testing.T) {
	long_names := make([]string, 12)
	fields := []domain.Field{
		{JSONName: "a_string", Kind: domain.KindString, MinLength: 2, MaxLength: 7},
		{JSONName: "b_number", Kind: domain.KindNumber},
		{JSONName: "c_integer", Kind: domain.KindInteger},
		{JSONName: "d_boolean", Kind: domain.KindBoolean},
		{JSONName: "e_enum", Kind: domain.KindEnum, Ref: "color"},
		{JSONName: "f_one", Kind: domain.KindEnum, Ref: "single"},
		{JSONName: "g_long", Kind: domain.KindEnum, Ref: "long"},
		{JSONName: "h_struct", Kind: domain.KindStruct, Ref: "demo_kinds_checked"},
		{JSONName: "i_attributes", Kind: domain.KindAttributes},
		{JSONName: "j_map", Kind: domain.KindMap},
		{JSONName: "k_" + strings.Repeat("n", 80), Kind: domain.KindBoolean},
	}
	for position := range long_names {
		fields = append(fields, domain.Field{JSONName: "required_field_with_a_long_name_" + string(rune('a'+position)), Kind: domain.KindString, Required: true})
	}
	long_values := make([]string, 12)
	for position := range long_values {
		long_values[position] = "a_rather_long_enum_value_" + string(rune('a'+position))
	}
	contract := domain.Contract{
		EventTypes: []domain.EventType{{Name: "demo.kinds.checked"}},
		Enums: []domain.Enum{
			{Name: "color", Source: "contracts/enums/color.json", Values: []string{"red", "dark green"}},
			{Name: "single", Source: "contracts/enums/single.json", Values: []string{"only"}},
			{Name: "long", Source: "contracts/enums/long.json", Values: long_values},
		},
		Attributes: domain.AttributesLimits{Source: "contracts/schemas/common/attributes.schema.json", MaxProperties: 5, MinKeyLength: 1, MaxKeyLength: 9, MaxStringLength: 11},
		Structs:    []domain.Struct{{Name: "demo_kinds_checked", Source: "contracts/schemas/demo/kinds_checked.schema.json", Closed: true, Fields: fields}},
	}
	files, render_error := python_renderer.NewValidationRenderer().Render(contract)
	if render_error != nil {
		test.Fatal(render_error)
	}
	content := string(files[0].Content)
	check_validation_style(test, content)
	for _, expected := range []string{
		"from typing import Any\n",
		"import (\n    AttributesLimits,\n",
		`FieldRule("a_string", check_string(2, 7)),`,
		`FieldRule("b_number", check_number),`,
		`FieldRule("c_integer", check_integer),`,
		`FieldRule("d_boolean", check_boolean),`,
		`FieldRule("e_enum", check_enum(("red", "dark green"))),`,
		`FieldRule("f_one", check_enum(("only",))),`,
		`FieldRule("h_struct", validate_demo_kinds_checked),`,
		`FieldRule("i_attributes", check_attributes(AttributesLimits(5, 1, 9, 11))),`,
		`FieldRule("j_map", check_object),`,
		"            closed=True,\n",
		"            required=(\n                \"required_field_with_a_long_name_a\",\n",
	} {
		if !strings.Contains(content, expected) {
			test.Errorf("the validators do not contain %q:\n%s", expected, content)
		}
	}
	if !strings.Contains(content, "FieldRule(\n                    \"g_long\",\n                    check_enum(\n                        (\n"+
		"                            \"a_rather_long_enum_value_a\",\n") {
		test.Errorf("an enum that does not fit in a line has one value per line:\n%s", content)
	}
	if !strings.Contains(content, "FieldRule(\"k_"+strings.Repeat("n", 80)+"\",\n                    check_boolean,\n                ),\n") {
		test.Errorf("a call that does not fit in a line is wrapped:\n%s", content)
	}
}

func TestAnOpenStructWithOneFieldIsRenderedWithoutRequiredOrClosed(test *testing.T) {
	contract := domain.Contract{
		EventTypes: []domain.EventType{{Name: "demo.one.field"}},
		Structs: []domain.Struct{{Name: "demo_one_field", Source: "contracts/schemas/demo/one_field.schema.json",
			Fields: []domain.Field{{JSONName: "x", Kind: domain.KindBoolean}}}},
	}
	files, render_error := python_renderer.NewValidationRenderer().Render(contract)
	if render_error != nil {
		test.Fatal(render_error)
	}
	content := string(files[0].Content)
	if strings.Contains(content, "required=") || strings.Contains(content, "closed=") {
		test.Errorf("content:\n%s", content)
	}
	check_validation_style(test, content)
}
