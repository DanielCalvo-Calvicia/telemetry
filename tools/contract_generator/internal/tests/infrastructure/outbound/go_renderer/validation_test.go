func TestTheFixtureContractRendersTheExpectedGoValidators(test *testing.T) {
	contract, read_error := contract_folder.NewReader(external.NewFolder(fixtures.ContractDir())).Read()
	if read_error != nil {
		test.Fatal(read_error)
	}
	files, render_error := go_renderer.NewValidationRenderer().Render(contract.Sorted())
	if render_error != nil {
		test.Fatal(render_error)
	}
	if len(files) != 1 || files[0].Name != "event_validators_generated.go" {
		test.Fatalf("files: %+v", files)
	}
	if expected := fixtures.Expected(test, "go/event_validators_generated.go.golden"); string(files[0].Content) != expected {
		test.Errorf("the validators differ from their expected file:\n%s", files[0].Content)
	}
	content := string(files[0].Content)
	if !strings.HasPrefix(content, "// Code generated by contract_generator; DO NOT EDIT.\n// Source: contracts/enums/severity.json\n") ||
		!strings.Contains(content, "package event_validation\n") {
		test.Errorf("the header is wrong:\n%s", content)
	}
	if formatted, _ := format.Source(files[0].Content); string(formatted) != content {
		test.Error("the validators are not gofmt-clean")
	}
}

func TestAContractWithNoEventTypeRendersAnEmptyTable(test *testing.T) {
	files, render_error := go_renderer.NewValidationRenderer().Render(domain.Contract{})
	if render_error != nil {
		test.Fatal(render_error)
	}
	content := string(files[0].Content)
	if !strings.Contains(content, "var event_validators = map[string]Validator{}") || strings.Contains(content, "func validate_") {
		test.Errorf("content:\n%s", content)
	}
}

func TestEveryKindOfFieldHasItsCheck(test *testing.T) {
	contract := domain.Contract{
		EventTypes: []domain.EventType{{Name: "demo.kinds.checked"}},
		Enums:      []domain.Enum{{Name: "color", Source: "contracts/enums/color.json", Values: []string{"red", "dark green"}}},
		Attributes: domain.AttributesLimits{Source: "contracts/schemas/common/attributes.schema.json", MaxProperties: 5, MinKeyLength: 1, MaxKeyLength: 9, MaxStringLength: 11},
		Structs: []domain.Struct{{Name: "demo_kinds_checked", Source: "contracts/schemas/demo/kinds_checked.schema.json", Fields: []domain.Field{
			{JSONName: "a_string", Kind: domain.KindString, MinLength: 2, MaxLength: 7},
			{JSONName: "b_number", Kind: domain.KindNumber},
			{JSONName: "c_integer", Kind: domain.KindInteger, Required: true},
			{JSONName: "d_boolean", Kind: domain.KindBoolean},
			{JSONName: "e_enum", Kind: domain.KindEnum, Ref: "color"},
			{JSONName: "f_struct", Kind: domain.KindStruct, Ref: "demo_kinds_checked"},
			{JSONName: "g_attributes", Kind: domain.KindAttributes},
			{JSONName: "h_map", Kind: domain.KindMap},
		}}},
	}
	files, render_error := go_renderer.NewValidationRenderer().Render(contract)
	if render_error != nil {
		test.Fatal(render_error)
	}
	content := string(files[0].Content)
	for _, expected := range []string{
		`Required: []string{"c_integer"}`,
		"CheckString(2, 7)",
		"CheckNumber}",
		"CheckInteger}",
		"CheckBoolean}",
		`CheckEnum("red", "dark green")`,
		"Check: validate_demo_kinds_checked}",
		"CheckAttributes(AttributesLimits{MaxProperties: 5, MinKeyLength: 1, MaxKeyLength: 9, MaxStringLength: 11})",
		"CheckObject}",
	} {
		if !strings.Contains(content, expected) {
			test.Errorf("the validators do not contain %q:\n%s", expected, content)
		}
	}
	if strings.Contains(content, "Closed") {
		test.Error("an open struct has no Closed rule")
	}
}

func TestAnInvalidStructNameIsARenderError(test *testing.T) {
	contract := domain.Contract{
		EventTypes: []domain.EventType{{Name: "bad name.x.y"}},
		Structs:    []domain.Struct{{Name: "bad name_x_y", Source: "contracts/schemas/bad.schema.json"}},
	}
	_, render_error := go_renderer.NewValidationRenderer().Render(contract)
	if render_error == nil || !strings.Contains(render_error.Error(), "event_validators_generated.go") {
		test.Errorf("error %v", render_error)
	}
}
